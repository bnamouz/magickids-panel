export type Mode = 'off' | 'shadow' | 'on';
export function parseMode(value: string | undefined): Mode {
  const v = String(value ?? '').trim().toLowerCase();
  return v === 'off' || v === 'on' ? v : 'shadow';
}

export type BotConfig = {
  mode: Mode;
  chatCap: number;
  windowMinutes: number;
  globalCap: number;
  takeoverHours: number;
  ignore: string[];
};
function int(value: string | undefined, fallback: number, min: number, max: number) {
  const n = Number.parseInt(String(value ?? ''), 10);
  return Number.isFinite(n) && n >= min && n <= max ? n : fallback;
}
export function readConfig(env: Record<string, string | undefined> = process.env): BotConfig {
  return {
    mode: parseMode(env.INSTITUTE_WA_AUTOREPLY),
    chatCap: int(env.INSTITUTE_WA_CHAT_CAP, 5, 1, 20),
    windowMinutes: int(env.INSTITUTE_WA_CHAT_WINDOW_MINUTES, 60, 5, 1440),
    globalCap: int(env.INSTITUTE_WA_GLOBAL_CAP, 60, 1, 1000),
    takeoverHours: int(env.INSTITUTE_WA_TAKEOVER_HOURS, 12, 1, 168),
    ignore: String(env.INSTITUTE_WA_IGNORE ?? '').split(/[,\s]+/).map(identity).filter(Boolean),
  };
}

/** Digits of a WhatsApp id or phone, with local 05X normalised to 9725X. */
export function identity(value: unknown): string {
  const raw = String(value ?? '').split('@')[0].split(':')[0];
  const digits = raw.replace(/\D/g, '');
  return /^05\d{8}$/.test(digits) ? `972${digits.slice(1)}` : digits;
}

export function isTrue(value: unknown) {
  return value === true || value === 1 || value === 'true' || value === '1';
}

/** Constant-time comparison of the ?key= secret. Empty or missing secret never matches. */
export function secretMatches(given: string | null | undefined, expected: string | undefined): boolean {
  if (!expected || !given) return false;
  const a = createHash('sha256').update(given).digest();
  const b = createHash('sha256').update(expected).digest();
  return timingSafeEqual(a, b) && given.length === expected.length;
}

/** UltraMsg sends instanceId as "173060"; env holds "instance173060". */
export function instanceMatches(bodyInstance: unknown, envInstance: string | undefined) {
  const a = String(bodyInstance ?? '').replace(/\D/g, ''), b = String(envInstance ?? '').replace(/\D/g, '');
  return !!a && a === b;
}

export type WaEvent = {
  event: string;
  instanceId: string;
  providerId: string | null;
  referenceId: string | null;
  fromMe: boolean;
  from: string;
  to: string;
  author: string;
  chatId: string;       // the other party's raw id (customer)
  chatPhone: string;    // identity(chatId)
  name: string;
  type: string;
  body: string;
};

export function parseEvent(payload: any): WaEvent | null {
  if (!payload || typeof payload !== 'object' || !payload.data || typeof payload.data !== 'object') return null;
  const d = payload.data;
  const fromMe = [d.fromMe, d.self, payload.fromMe].some(isTrue);
  const from = String(d.from ?? ''), to = String(d.to ?? '');
  const chatId = fromMe ? to : from;
  const providerId = d.id != null && String(d.id).trim() ? String(d.id).trim().slice(0, 200) : null;
  const ref = payload.referenceId ?? d.referenceId;
  return {
    event: String(payload.event_type ?? payload.type ?? ''),
    instanceId: String(payload.instanceId ?? payload.instance_id ?? ''),
    providerId,
    referenceId: ref != null && String(ref).trim() ? String(ref).trim().slice(0, 80) : null,
    fromMe,
    from, to,
    author: String(d.author ?? ''),
    chatId,
    chatPhone: identity(chatId),
    name: String(d.pushname ?? d.notifyName ?? '').slice(0, 160),
    type: String(d.type ?? 'chat').slice(0, 40) || 'chat',
    body: typeof d.body === 'string' ? d.body.slice(0, 8000) : '',
  };
}

export function isGeneratedEnvelope(text: string) {
  return GENERATED_PATTERNS.some((re) => re.test(String(text ?? '')));
}

export function isInternalName(name: string) {
  const n = String(name ?? '').trim().toLowerCase();
  return !!n && INTERNAL_NAMES.includes(n);
}

/**
 * Why an event must be ignored entirely (no reply, no takeover), or null if it
 * belongs to a direct 1:1 chat with a family. Applies to both directions.
 */
export function ignoreReason(e: WaEvent, cfg: Pick<BotConfig, 'ignore'>): string | null {
  if (!['message_received', 'message_create'].includes(e.event)) return 'not_message_event';
  if (!e.providerId) return 'no_provider_id';
  const ids = [e.from, e.to, e.author, e.chatId].map(String);
  if (ids.some((v) => /@g\.us|@newsletter|@broadcast|status@|newsletter|broadcast/i.test(v))) return 'non_direct';
  if (!/@c\.us$/i.test(e.chatId)) return 'non_direct';           // @lid aliases and unknown forms: never auto-answered
  if (!/^\d{8,15}$/.test(e.chatPhone)) return 'invalid_chat';
  const blocked = new Set([INSTITUTE_NUMBER, ...INTERNAL_NUMBERS, ...cfg.ignore]);
  if (blocked.has(e.chatPhone) || (e.author && blocked.has(identity(e.author)) && !e.fromMe)) return 'internal_number';
  if (!e.fromMe && identity(e.from) === INSTITUTE_NUMBER) return 'internal_number';
  if (!e.fromMe && isInternalName(e.name)) return 'internal_name';
  if (!e.fromMe && isGeneratedEnvelope(e.body)) return 'bot_envelope';
  return null;
}

/** Classifies an outgoing (fromMe) event: our own reply echo, or staff typing in the chat. */
export function classifyOutgoing(e: WaEvent, recentBot: { reference_id: string | null; body: string | null }[]): 'bot_echo' | 'staff' {
  if (e.body.includes(BOT_MARKER)) return 'bot_echo';
  if (e.referenceId && (e.referenceId.startsWith('mkbot-') || recentBot.some((r) => r.reference_id === e.referenceId))) return 'bot_echo';
  const norm = (s: string | null) => String(s ?? '').replace(/[\u200b\u2063\s]+/g, ' ').trim();
  if (e.body && recentBot.some((r) => norm(r.body) === norm(e.body))) return 'bot_echo';
  return 'staff';
}

const TEXT_TYPES = new Set(['chat', 'text']);
export function isTextMessage(e: WaEvent) {
  return TEXT_TYPES.has(e.type) && e.body.trim().length > 0;
}

/** Hebrew vs Arabic by script; ties and Latin text default to Hebrew. */
export function detectLanguage(text: string): 'he' | 'ar' {
  const ar = (text.match(/[\u0600-\u06ff]/g) ?? []).length;
  const he = (text.match(/[\u0590-\u05ff]/g) ?? []).length;
  return ar > he ? 'ar' : 'he';
}

/** Deterministic escalation triggers, in addition to the model's needs_staff. */
const STAFF_PATTERNS: [RegExp, string][] = [
  [/דחוף|חירום|מצב חירום|בהול|طوارئ|طارئ|مستعجل|ضروري كتير|عاجل/u, 'urgent'],
  [/תלונה|להתלונן|לא מרוצה|גרוע|شكوى|بدّي اشتكي|بدي اشتكي|مش مبسوط/u, 'complaint'],
  [/מסמך|סיכום|דו"ח|דוח|דו״ח|טופס 17|התחייבות|אישור רפואי|מכתב|תעודה|מרשם|تقرير|ملخص|مستند|وثيقة|تحويل|التزام|نموذج 17|وصفة|رسالة من الدكتور/u, 'document_request'],
];
export function staffTrigger(text: string): string | null {
  for (const [re, reason] of STAFF_PATTERNS) if (re.test(text)) return reason;
  return null;
}

/** Institute office hours used only for the out-of-hours note (Asia/Jerusalem). */
export function isOfficeHours(now: Date): boolean {
  const parts = new Intl.DateTimeFormat('en-US', { timeZone: 'Asia/Jerusalem', weekday: 'short', hour: 'numeric', minute: 'numeric', hourCycle: 'h23' }).formatToParts(now);
  const get = (t: string) => parts.find((p) => p.type === t)?.value ?? '';
  const day = get('weekday'), minutes = Number(get('hour')) * 60 + Number(get('minute'));
  if (['Sun', 'Mon', 'Tue', 'Wed', 'Thu'].includes(day)) return minutes >= 9 * 60 && minutes < 19 * 60;
  if (day === 'Fri') return minutes >= 9 * 60 && minutes < 13 * 60;
  return false;
}
